abstract final class FailureCodes {
  static const timeout = 'timeout';
  static const noInternet = 'no_internet';
  static const requestCancelled = 'request_cancelled';
  static const unknown = 'unknown';
  static const serverError = 'server_error';
  static const invalidCredentials = 'invalid_credentials';
  static const accessForbidden = 'access_forbidden';
  static const resourceNotFound = 'resource_not_found';
  static const resourceExists = 'resource_exists';
  static const validationFailed = 'validation_failed';
}
